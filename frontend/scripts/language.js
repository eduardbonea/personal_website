let currentLang = "en";
const langBtn = document.getElementById("lang-btn");

langBtn.addEventListener("click", () => {
  currentLang = currentLang === "en" ? "ro" : "en";
  langBtn.innerText = currentLang === "en" ? "RO" : "EN";

  document.querySelectorAll("[lang-translate]").forEach((el) => {
    const key = el.getAttribute("lang-translate");
    const translation = translations[currentLang][key];

    if (translation) {
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
        el.setAttribute("placeholder", translation);

        if (el.hasAttribute("required")) {
          const errorMsg =
            currentLang === "en"
              ? "Please fill out this field."
              : "Te rog completează acest câmp.";
          el.oninvalid = (e) => e.target.setCustomValidity(errorMsg);
          el.oninput = (e) => e.target.setCustomValidity("");
        }
      } else {
        el.innerHTML = translation;
      }
    }
  });
});
